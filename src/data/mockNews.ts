// Функция для генерации случайной даты за последний год
const getRandomDate = () => {
  const now = new Date();
  const past = new Date(now.getFullYear() - 1, now.getMonth(), now.getDate());
  const randomTime = past.getTime() + Math.random() * (now.getTime() - past.getTime());
  return new Date(randomTime).toISOString();
};

// Функция для генерации случайного элемента из массива
const getRandomElement = <T>(array: T[]): T => {
  return array[Math.floor(Math.random() * array.length)];
};

// Генерация 100+ новостей
export const generateMockNews = (count: number = 100): INews[] => {
  const news: INews[] = [];
  
  for (let i = 1; i <= count; i++) {
    const title = getRandomElement(newsTitles);
    const description = getRandomElement(newsDescriptions);
    const source = getRandomElement(sources);
    const category = getRandomElement(categories);
    
    news.push({
      id: `news-${i}`,
      title: `${title} - часть ${i}`,
      description: `${description} Это новость номер ${i} в нашей ленте.`,
      url: `#news-${i}`,
      urlToImage: `https://picsum.photos/400/300?random=${i}&sig=${Math.random()}`,
      publishedAt: getRandomDate(),
      source: { name: source },
      category: category
    });
  }
  
  return news;
};

